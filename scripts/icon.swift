// Draws the app icon: a monitor whose screen holds two inputs, the switch between them an accent arrow,
// a white power light on the bezel. Writes the iOS AppIcon, public/icon.svg and public/icon-180/192/512.png.
// Run: swift scripts/icon.swift
import AppKit
import SwiftUI

// One set of numbers (1024 grid) feeds both the SwiftUI drawing and the SVG.
let screen = CGRect(x: 252, y: 298, width: 520, height: 340), screenRadius: CGFloat = 28
let neck = (CGPoint(x: 512, y: 638), CGPoint(x: 512, y: 726))
let base = (CGPoint(x: 412, y: 726), CGPoint(x: 612, y: 726))
let inputs = [CGRect(x: 307, y: 413, width: 110, height: 110), CGRect(x: 607, y: 413, width: 110, height: 110)]
let inputRadius: CGFloat = 16
let arrow = [CGPoint(x: 451, y: 468), CGPoint(x: 573, y: 468)], arrowHead = [CGPoint(x: 535, y: 430), CGPoint(x: 573, y: 468), CGPoint(x: 535, y: 506)]
let led = CGRect(x: 724, y: 594, width: 22, height: 22)
let stroke: CGFloat = 12, arrowStroke: CGFloat = 26
let accentHex = "#346bf1"
let accent = Color(red: 0x34 / 255, green: 0x6b / 255, blue: 0xf1 / 255)

struct Icon: View {
    var body: some View {
        ZStack {
            // Full-bleed, opaque: iOS and browsers apply their own mask.
            LinearGradient(colors: [Color(white: 0.09), Color(white: 0.02)], startPoint: .top, endPoint: .bottom)
            Canvas { ctx, _ in
                let line = GraphicsContext.Shading.color(.white.opacity(0.55))
                let round = StrokeStyle(lineWidth: stroke, lineCap: .round, lineJoin: .round)
                ctx.stroke(Path(roundedRect: screen, cornerRadius: screenRadius), with: line, style: round)
                ctx.stroke(Path { $0.move(to: neck.0); $0.addLine(to: neck.1); $0.move(to: base.0); $0.addLine(to: base.1) }, with: line, style: round)
                for r in inputs { ctx.stroke(Path(roundedRect: r, cornerRadius: inputRadius), with: line, style: round) }
                ctx.stroke(Path { $0.addLines(arrow); $0.addLines(arrowHead) }, with: .color(accent),
                           style: StrokeStyle(lineWidth: arrowStroke, lineCap: .round, lineJoin: .round))
                ctx.fill(Path(ellipseIn: led), with: .color(.white))
            }
        }
        .frame(width: 1024, height: 1024)
    }
}

@MainActor func png(_ px: Int) -> Data {
    let r = ImageRenderer(content: Icon())
    r.scale = CGFloat(px) / 1024
    r.isOpaque = true
    let rep = NSBitmapImageRep(cgImage: r.cgImage!)
    assert(rep.pixelsWide == px && !rep.hasAlpha, "icon must be \(px) px and opaque")
    return rep.representation(using: .png, properties: [:])!
}

func pts(_ p: [CGPoint]) -> String { p.map { "\(Int($0.x)) \(Int($0.y))" }.joined(separator: " L") }
func rect(_ r: CGRect, _ rx: CGFloat) -> String {
    "<rect x=\"\(Int(r.minX))\" y=\"\(Int(r.minY))\" width=\"\(Int(r.width))\" height=\"\(Int(r.height))\" rx=\"\(Int(rx))\"/>"
}
// Browsers show the SVG as is, so it gets the rounded tile and the 8% hairline.
let svg = """
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!-- Generated by scripts/icon.swift; edit the script, not this file. -->
  <defs><linearGradient id="tile" x2="0" y2="1"><stop offset="0" stop-color="#171717"/><stop offset="1" stop-color="#050505"/></linearGradient></defs>
  <rect width="1024" height="1024" rx="228" fill="url(#tile)"/>
  <rect x="2" y="2" width="1020" height="1020" rx="226" fill="none" stroke="#fff" stroke-opacity=".08" stroke-width="4"/>
  <g fill="none" stroke="#fff" stroke-opacity=".55" stroke-width="\(Int(stroke))" stroke-linecap="round" stroke-linejoin="round">
    \(rect(screen, screenRadius))
    <path d="M\(pts([neck.0, neck.1])) M\(pts([base.0, base.1]))"/>
    \(inputs.map { rect($0, inputRadius) }.joined(separator: "\n    "))
  </g>
  <path d="M\(pts(arrow)) M\(pts(arrowHead))" fill="none" stroke="\(accentHex)" stroke-width="\(Int(arrowStroke))" stroke-linecap="round" stroke-linejoin="round"/>
  <circle cx="\(Int(led.midX))" cy="\(Int(led.midY))" r="\(Int(led.width / 2))" fill="#fff"/>
</svg>

"""

let root = URL(fileURLWithPath: CommandLine.arguments[0]).deletingLastPathComponent().deletingLastPathComponent()
let outputs: [(String, Int)] = [
    ("ios/MonitorSwitch/Assets.xcassets/AppIcon.appiconset/icon-1024.png", 1024),
    ("public/icon-512.png", 512), ("public/icon-192.png", 192), ("public/icon-180.png", 180),
]
for (path, px) in outputs { try MainActor.assumeIsolated { png(px) }.write(to: root.appending(path: path)) }
try svg.write(to: root.appending(path: "public/icon.svg"), atomically: true, encoding: .utf8)
// The manifest colors follow the tile.
let manifestURL = root.appending(path: "public/manifest.json")
var manifest = try String(contentsOf: manifestURL, encoding: .utf8)
for key in ["background_color", "theme_color"] {
    manifest = manifest.replacingOccurrences(of: "\"\(key)\": \"#[0-9a-fA-F]+\"", with: "\"\(key)\": \"#000000\"", options: .regularExpression)
}
try manifest.write(to: manifestURL, atomically: true, encoding: .utf8)
print((outputs.map(\.0) + ["public/icon.svg", "public/manifest.json"]).joined(separator: "\n"))
